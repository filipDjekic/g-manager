test('theme density and responsive navigation remain usable at configured viewport', async ({ page }) => {
  await installApi(page, 'CUSTOMER')
  await login(page, 'CUSTOMER')
  const width = page.viewportSize()?.width ?? 1280
  await page.getByRole('button', { name: /^Moj nalog:/ }).click()
  const preferences = page.getByRole('dialog', { name: 'Moj nalog' })
  await preferences.getByLabel('Tema').selectOption('light')
  await preferences.getByLabel('Gustina prikaza').selectOption('compact')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(page.locator('html')).toHaveAttribute('data-density', 'compact')

  if (width <= 800) {
    const menu = page.getByRole('button', { name: 'Meni', exact: true })
    await expect(menu).toBeVisible()
    await menu.click()
    await expect(page.getByRole('dialog', { name: 'Navigacija' })).toBeVisible()
    await page.getByRole('dialog', { name: 'Navigacija' }).getByRole('link', { name: 'Ponuda', exact: true }).click()
  } else {
    await page.getByRole('navigation', { name: 'Glavna navigacija' }).getByRole('link', { name: 'Ponuda', exact: true }).click()
  }
  await expect(page.getByRole('heading', { name: 'Ponuda', exact: true })).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
  expect(overflow).toBe(false)
})

