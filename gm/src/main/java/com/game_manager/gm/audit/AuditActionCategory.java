package com.game_manager.gm.audit;

import java.util.List;
import java.util.Set;

public enum AuditActionCategory {
    CREATE(Set.of("USER_CREATED", "CUSTOMER_CREATED", "CATALOG_CREATED",
            "CUSTOMER_CRM_NOTE_CREATED", "WORKING_HOURS_EXCEPTION_CREATED", "TIME_OFF_CREATED",
            "WAITLIST_CREATED", "APPLICATION_DEFINITION_CREATED", "APPLICATION_PROFILE_CREATED",
            "MACHINE_ENROLLMENT_TOKEN_CREATED", "GAMING_SESSION_STARTED", "DOCUMENT_UPLOADED",
            "REPORT_REQUESTED", "WORKFLOW_STARTED")),
    UPDATE(Set.of("USER_PROFILE_UPDATED", "USER_PASSWORD_CHANGED", "USER_AVATAR_UPDATED",
            "USER_RESTORED", "CUSTOMER_UPDATED", "CATALOG_UPDATED", "CATALOG_IMAGE_UPDATED",
            "CATALOG_ACTIVATED", "CATALOG_RESTORED", "CUSTOMER_CRM_NOTE_UPDATED",
            "CUSTOMER_CRM_TAG_ADDED", "CUSTOMER_CRM_TAG_REMOVED", "WORKING_HOURS_UPDATED",
            "WORKING_HOURS_EXCEPTION_UPDATED", "TIME_OFF_APPROVED", "TIME_OFF_REJECTED",
            "TIME_OFF_CANCELLED", "WAITLIST_UPDATED", "WAITLIST_CANCELLED",
            "APPLICATION_DEFINITION_UPDATED", "APPLICATION_PROFILE_UPDATED", "STATION_PROFILE_UPDATED",
            "GAMING_SESSION_EXTENDED", "GAMING_SESSION_TERMINATED", "ORDER_STATUS_CHANGED",
            "RESERVATION_STATUS_CHANGED", "RESERVATION_RESOURCE_ASSIGNED", "RESERVATION_UPDATED",
            "EMPLOYEE_RESOURCE_ACCESS_CHANGED", "EMPLOYEE_LOCATION_ACCESS_CHANGED",
            "FEATURE_FLAG_UPDATED", "DOCUMENT_VERSION_UPLOADED", "DOCUMENT_RESTORED",
            "WORKFLOW_DEFINITION_PUBLISHED", "WORKFLOW_DECISION", "AI_REPORT_SUMMARY_FEEDBACK")),
    DELETE(Set.of("USER_DELETED", "CATALOG_DELETED", "CUSTOMER_CRM_NOTE_DELETED",
            "WORKING_HOURS_EXCEPTION_DELETED", "APPLICATION_DEFINITION_DELETED",
            "APPLICATION_PROFILE_DELETED", "DOCUMENT_DELETED")),
    DEACTIVATE(Set.of("USER_DEACTIVATED", "CUSTOMER_DEACTIVATED", "CATALOG_DEACTIVATED",
            "MACHINE_IDENTITIES_REVOKED")),
    OTHER(Set.of());

    private final Set<String> actions;

    AuditActionCategory(Set<String> actions) { this.actions = actions; }

    public List<String> actions() { return actions.stream().sorted().toList(); }

    public static AuditActionCategory of(String action) {
        for (AuditActionCategory category : values()) {
            if (category.actions.contains(action)) return category;
        }
        return OTHER;
    }
}
